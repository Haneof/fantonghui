_CN_DIGITS: Final[dict[str, int]] = {
    "一": 1, "二": 2, "两": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9, "十": 10,
}

_CLOCK_RE: Final[re.Pattern[str]] = re.compile(
    r"(?P<period>凌晨|清晨|早上|上午|中午|下午|傍晚|晚上|深夜|夜里|晚)?\s*"
    r"(?:(?P<h_ar>\d{1,2})[:：](?P<m_ar>\d{2})"
    r"|(?P<h_cn>[一二三四五六七八九十两]{1,3})\s*点\s*"
    r"(?P<m_cn>半|十几分?|\d{1,2}分?|[一二三四五六七八九十]{1,3}分?)?)")

# 时段词 -> 允许的小时区间（左闭右开，允许跨零点用 24+ 表示）
CLOCK_PERIOD_HOURS: Final[dict[str, tuple[int, int]]] = {
    "凌晨": (0, 6), "清晨": (4, 9), "早上": (5, 10), "上午": (7, 12),
    "中午": (10, 15), "下午": (12, 18), "傍晚": (16, 20),
    "晚上": (17, 24), "晚": (17, 24), "深夜": (21, 30), "夜里": (18, 30),
}


def _cn_int(text: str) -> int | None:
    """解析 1~59 以内的中文数字（一 / 十一 / 十几 / 二十 / 四十）。"""
    if not text:
        return None
    if text in _CN_DIGITS:
        return _CN_DIGITS[text]
    if "十" in text:
        left, _, right = text.partition("十")
        tens = _CN_DIGITS.get(left, 1) if left else 1
        ones = _CN_DIGITS.get(right, 0) if right else 0
        return tens * 10 + ones
    return None


def _clock_minute_part(token: str) -> int:
    if not token:
        return 0
    if token == "半":
        return 30
    if token.startswith("十几") or token == "几":
        return 15
    digits = token.rstrip("分")
    if digits.isdigit():
        return min(59, int(digits))
    value = _cn_int(digits)
    return 0 if value is None else min(59, value)


def iter_clock_candidates(text: str) -> list[int]:
    """抽取文案中所有可能的一天内钟点（含上午/下午/次日的候选解，单位：分钟）。

    用途：组卷时把切片时间戳对齐到文案钟点；校验时确认两者至少有一种解释自洽。
    """
    candidates: list[int] = []
    for match in _CLOCK_RE.finditer(text):
        hour = int(match.group("h_ar")) if match.group("h_ar") else _cn_int(match.group("h_cn") or "")
        if hour is None or not 0 <= hour <= 23:
            continue
        minute = _clock_minute_part(match.group("m_ar") or match.group("m_cn") or "")
        base = hour * 60 + minute
        # 24 小时制写法（16:20）无 12 小时歧义；"八点"这类中文写法才需要上午/下午双解
        options = [base, base + 1440] if match.group("h_ar") else [base, base + 720, base + 1440]
        period = match.group("period")
        if period and period in CLOCK_PERIOD_HOURS:
            low, high = CLOCK_PERIOD_HOURS[period]
            narrowed = [item for item in options if low * 60 <= item < high * 60]
            if narrowed:
                options = narrowed
        candidates.extend(options)
    return candidates


def circular_minute_gap(left: int, right: int) -> int:
    """两个分钟值在 24 小时表盘上的最近距离。"""
    gap = abs(left - right) % (24 * 60)
    return min(gap, 24 * 60 - gap)


def resolve_clock_minute(text: str, reference: int | None = None) -> int | None:
    """把文案里的钟点解析为具体分钟；有参考时间时取最接近的候选解释。"""
    candidates = iter_clock_candidates(text)
    if not candidates:
        return None
    if reference is None:
        daytime = [item for item in candidates if 5 * 60 + 30 <= item < 24 * 60]
        return min(daytime) if daytime else min(candidates)
    # 参考值本身可能就是 24h+ 的绝对分钟（如 26:30 表示次日 02:30），故用线性距离，
    # 避免 02:30 与其折叠解被误判为等距而破坏时间轴排序。
    return min(candidates, key=lambda item: abs(item - reference))

