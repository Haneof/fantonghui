def section(text: str, start_marker: str) -> str:
    """取 start_marker 起，到下一个同级/更高级标题止。"""
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith(start_marker))
    level = len(start_marker) - len(start_marker.lstrip("#"))
    end = len(lines)
    for i in range(start + 1, len(lines)):
        m = re.match(r"^(#+)\s", lines[i])
        if m and len(m.group(1)) <= level:
            end = i
            break
    seg = lines[start:end]
    while seg and seg[-1].strip() in ("", "---"):
        seg.pop()
    return "\n".join(seg)


def to_end(text: str, start_marker: str) -> str:
    lines = text.split("\n")
    start = next(i for i, l in enumerate(lines) if l.startswith(start_marker))
    seg = lines[start:]
    while seg and seg[-1].strip() in ("", "---"):
        seg.pop()
    return "\n".join(seg)


def demote(md: str, by: int = 1) -> str:
    out = []
    for line in md.split("\n"):
        m = re.match(r"^(#+)(\s)", line)
        out.append("#" * (len(m.group(1)) + by) + line[len(m.group(1)):] if m else line)
    return "\n".join(out)


